def spelled(word: str) -> str:
    return "-".join(word)


def join_positions(positions: list[int]) -> str:
    text = [str(p) for p in positions]
    if len(text) == 1:
        return text[0]
    return ", ".join(text[:-1]) + " and " + text[-1]


def pick_letter(word: str) -> str:
    counts = {c: word.count(c) for c in set(word) if c != "l"}
    best = max(counts.values())
    return min(c for c, n in counts.items() if n == best)


def count_example(word: str, letter: str, template: str) -> dict:
    positions = [i + 1 for i, c in enumerate(word) if c == letter]
    question = template.format(x=letter, X=letter.upper(), w=word)
    if not positions:
        answer = (
            f'There are 0 {letter.upper()}\'s in "{word}". '
            f"Spelling it out ({spelled(word)}) shows none."
        )
    elif len(positions) == 1:
        answer = (
            f'There is 1 {letter.upper()} in "{word}". '
            f"Spelling it out: {spelled(word)}. It is letter {positions[0]}."
        )
    else:
        answer = (
            f'There are {len(positions)} {letter.upper()}\'s in "{word}". '
            f"Spelling it out: {spelled(word)}. "
            f"The {letter.upper()}'s are letters {join_positions(positions)}."
        )
    return qa(question, answer)


def qa(question: str, answer: str) -> dict:
    return {
        "messages": [
            {"role": "user", "content": question},
            {"role": "assistant", "content": answer},
        ]
    }


def generated_examples() -> list[dict]:
    rng = random.Random(7)
    rows = []
    for i, word in enumerate(COUNT_WORDS):
        rows.append(
            count_example(
                word, pick_letter(word), COUNT_TEMPLATES[i % len(COUNT_TEMPLATES)]
            )
        )
    for word, letter in [("banana", "z"), ("mississippi", "b"), ("broccoli", "t"),
                         ("pineapple", "q"), ("zucchini", "a"), ("kangaroo", "s")]:  # fmt: skip
        rows.append(count_example(word, letter, rng.choice(COUNT_TEMPLATES)))
    for word in COUNT_WORDS[:20]:
        vowels = [c for c in word if c in "aeiou"]
        rows.append(
            qa(
                f'How many vowels are in "{word}"?',
                f'There are {len(vowels)} vowels in "{word}": '
                f"{', '.join(vowels)}. Spelling it out: {spelled(word)}.",
            )
        )
    for word in REVERSE_WORDS:
        rows.append(
            qa(
                f'Spell "{word}" backwards.',
                f'{word[::-1]}. Reading "{word}" ({spelled(word)}) from the last '
                f"letter to the first gives {spelled(word[::-1])}.",
            )
        )
    for i, word in enumerate(COUNT_WORDS[20:35]):
        n = i % 8
        rows.append(
            qa(
                f'What is the {ORDINALS[n]} letter of "{word}"?',
                f'The {ORDINALS[n]} letter of "{word}" is "{word[n]}". '
                f"Spelling it out: {spelled(word)}.",
            )
        )
    return rows


