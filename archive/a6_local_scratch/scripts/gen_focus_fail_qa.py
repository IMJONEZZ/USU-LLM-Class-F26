#!/usr/bin/env python3
"""Focused failure-skill Q&A for A6 continue-from-continue training."""

from __future__ import annotations

import json
import random
from collections import Counter
from pathlib import Path

from src.trainer import (
    find_graded_leakage,
    find_split_contamination,
    validate_qa_record,
)

rng = random.Random(42)
OUT = Path("data/assignment6/qa")
rows: list[dict] = []


def add(cat: str, instruction: str, response: str, i: int) -> None:
    rows.append(
        {
            "example_id": f"focus:{cat}:{i:04d}",
            "instruction": instruction.strip(),
            "response": response.strip(),
            "category": cat,
            "source": "focus:skill",
            "review_status": "approved",
        }
    )


def main() -> None:
    OUT.mkdir(parents=True, exist_ok=True)
    build_trump()
    build_christmas()
    build_letters()
    build_sphinx()
    build_knuckles()
    build_feathers()
    build_keepers()

    print("raw_rows", len(rows))
    kept, leaks = [], []
    for r in rows:
        validate_qa_record(r)
        issue = find_graded_leakage([r])
        if issue:
            leaks.append((r["example_id"], issue[0]))
        else:
            kept.append(r)
    print("kept", len(kept), "leaked_filtered", len(leaks))
    if leaks[:8]:
        print("sample_leaks", leaks[:8])

    seen: set[str] = set()
    uniq = []
    for r in kept:
        key = " ".join(r["instruction"].lower().split())
        if key in seen:
            continue
        seen.add(key)
        uniq.append(r)
    print("unique", len(uniq))
    cats = Counter(r["category"] for r in uniq)
    print("categories", dict(cats))

    rng.shuffle(uniq)
    n_dev = max(40, len(uniq) // 10)
    dev, train = uniq[:n_dev], uniq[n_dev:]
    contam = find_split_contamination(train, dev)
    if contam:
        raise SystemExit(f"contamination {contam[:3]}")
    assert not find_graded_leakage(train + dev)

    train_path = OUT / "focus_fail_train.jsonl"
    dev_path = OUT / "focus_fail_dev.jsonl"
    with train_path.open("w", encoding="utf-8") as f:
        for r in train:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    with dev_path.open("w", encoding="utf-8") as f:
        for r in dev:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    meta = {
        "train": len(train),
        "dev": len(dev),
        "categories": dict(cats),
        "leaks_filtered": len(leaks),
        "purpose": "focused continue on failing graded skills; init from continue adapter",
    }
    (OUT / "focus_fail_meta.json").write_text(json.dumps(meta, indent=2) + "\n")
    print("wrote", train_path, len(train))
    print("wrote", dev_path, len(dev))
    print(json.dumps(meta, indent=2))


